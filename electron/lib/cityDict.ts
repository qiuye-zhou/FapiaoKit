/**
 * 火车站名简化为城市名：上海虹桥→上海，北京南→北京，武汉→武汉
 * 优先匹配城市词典前缀，避免误切（如"济南"不会被切成"济"）
 */
export function simplifyStation(name: string): string {
  const n = name.trim()
  if (!n) return n
  // 词典前缀匹配（长的优先，如"呼和浩特"先于"呼"）
  const sorted = [...CITIES].sort((a, b) => b.length - a.length)
  for (const c of sorted) {
    if (n === c || n.startsWith(c)) return c
  }
  // 未识别：去掉常见站名后缀
  return n.replace(/(虹桥|[东西南北站])$/, '')
}

/** 在文本中查找城市名（如从酒店销售方名称中提取"武汉"） */
export function findCityInText(text: string): string | null {
  const sorted = [...CITIES].sort((a, b) => b.length - a.length)
  for (const c of sorted) {
    if (text.includes(c)) return c
  }
  return null
}
